// -----------------------------------------------------------------------------
// thermal_model.v  -  first-order lumped thermal model (fixed point)
//
//   C * dT/dt = P - G(duty) * (T - T_amb)
//   G(duty)   = G_NAT + G_FAN * duty/256            [W/K]
//   Euler step: T <= T + (P - G*(T - T_amb)) * (dt/C)
//
// Number formats
//   temp_q, power_q : signed Q16.16  (value = integer / 65536)
//   G_NAT_Q, G_FAN_Q: unsigned Q8.8  (value = integer / 256)
//   DT_OVER_C       : unsigned Q0.16 (value = integer / 65536)
//
// Defaults match thermal_sim.py: C = 40 J/K, dt = 0.5 s  ->  dt/C = 0.0125
//   0.0125 * 65536 = 819.2 -> 819
//   0.15   * 256   = 38.4  -> 38
//   0.90   * 256   = 230.4 -> 231 (slightly higher to compensate duty/256
//                                  vs duty/255 at full speed)
//
// NOTE: every operand in the arithmetic below is declared signed so that the
// >>> shifts are true arithmetic shifts. Do not mix in unsigned operands.
// -----------------------------------------------------------------------------
`timescale 1ns / 1ps

module thermal_model #(
    parameter signed [31:0] T_AMB_Q    = 32'sd1638400,  // 25 C in Q16.16
    parameter        [15:0] G_NAT_Q    = 16'd38,
    parameter        [15:0] G_FAN_Q    = 16'd231,
    parameter        [15:0] DT_OVER_C  = 16'd819
)(
    input  wire                clk,
    input  wire                rst,
    input  wire                tick,      // one thermal time step (0.5 s) per pulse
    input  wire         [7:0]  duty,      // fan duty used for this step
    input  wire signed [31:0]  power_q,   // heat generated by component, Q16.16 W
    output reg  signed [31:0]  temp_q     // component temperature, Q16.16 C
);

    // effective cooling conductance, Q8.8 W/K
    wire [15:0] g_q = G_NAT_Q + ((G_FAN_Q * duty) >> 8);

    // widen everything to 48 bits, signed
    wire signed [47:0] g_s      = g_q;                 // zero-extended (unsigned source)
    wire signed [47:0] k_s      = DT_OVER_C;           // zero-extended (unsigned source)
    wire signed [47:0] p_s      = power_q;             // sign-extended
    wire signed [47:0] dtemp    = temp_q - T_AMB_Q;    // T - T_amb  (Q16.16)

    wire signed [47:0] removal  = (dtemp * g_s) >>> 8; // heat removed, Q16.16 W
    wire signed [47:0] net      = p_s - removal;       // net heating power, Q16.16 W
    wire signed [47:0] delta    = (net * k_s) >>> 16;  // temperature change, Q16.16 C

    always @(posedge clk) begin
        if (rst)
            temp_q <= T_AMB_Q;
        else if (tick)
            temp_q <= temp_q + delta[31:0];
    end
endmodule
